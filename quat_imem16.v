module quat_imem16(
  input  [3:0] addr,
  output [15:0] instr
);
  reg [15:0] mem [0:15];
  initial begin
    mem[0]  = 16'b0000_0000_0001_0010; // ADD r2=r0+r1
    mem[1]  = 16'b0110_0000_0000_0000; // NOP (wait for r2)
    mem[2]  = 16'b0110_0000_0000_0000; // NOP (wait for r2)
    mem[3]  = 16'b0011_0001_0000_0000; // MOV r0=r1
    mem[4]  = 16'b0011_0010_0000_0001; // MOV r1=r2
    mem[5]  = 16'b0110_0000_0000_0000; // NOP
    mem[6]  = 16'b0000_0000_0001_0010; // ADD r2=r0+r1
    mem[7]  = 16'b0110_0000_0000_0000; // NOP
    mem[8]  = 16'b0110_0000_0000_0000; // NOP
    mem[9]  = 16'b0011_0001_0000_0000; // MOV r0=r1
    mem[10] = 16'b0011_0010_0000_0001; // MOV r1=r2
    mem[11] = 16'b0110_0000_0000_0000; // NOP
    mem[12] = 16'b0000_0000_0001_0010; // ADD r2=r0+r1
    mem[13] = 16'b0110_0000_0000_0000; // NOP
    mem[14] = 16'b0110_0000_0000_0000; // NOP
    mem[15] = 16'b0110_0000_0000_0000; // NOP
    end
  assign instr = mem[addr];
endmodule
